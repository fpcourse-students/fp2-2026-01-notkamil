== 1.1. Вычитание и деление

Добавьте в язык операции вычитания и целочисленного деления:

1. отредактируйте синтаксическое дерево в "Lang.Syntax";
2. дополните реализацию интерпретатора выражений в "Lang.Semantics";
3. добавьте операторы, создающие соответствующие узлы AST, в "Lang.Embedding".

== 1.2. Объекты


вычисленными полями. Ознакомьтесь с примером задания функционального списка
'Lang.Programs.list123'.

== 1.3. Паттерн-матчинг

Реализуйте интерпретацию паттерн-матчинга ('Lang.Syntax.Match') в "Lang.Semantics". Семантика:

* ветки перебираются по порядку, выбирается первая подошедшая; если не подошла ни одна —
  ошибка (@error@);
* 'Lang.Syntax.ConstPat' подходит к равному числу;
* 'Lang.Syntax.VarPat' подходит к любому значению и связывает с ним имя; связывания
  из образца видны в теле ветки и затеняют одноимённые переменные снаружи;
* 'Lang.Syntax.CtorPat' подходит к объекту с тем же тегом и тем же числом полей,
  если каждый вложенный образец подходит к своему полю.
